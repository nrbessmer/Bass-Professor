#!/usr/bin/env python3
"""
embed_logo.py — Bass Professor logo embedder
============================================
Converts Source/logo.png into Source/LogoBinaryData.h, a C++ header containing
the PNG bytes as a compile-time array.

Usage:
  1. Copy your Bass Professor logo PNG to:
       /path/to/BassProfessor/Source/logo.png

  2. Run this script from the Source folder (or any folder — it uses relative
     paths from its own location):
       python3 Source/embed_logo.py

  3. Rebuild the Xcode project. The logo will appear in the plugin header.

The editor code in PluginEditor.cpp auto-detects LogoBinaryData.h via
__has_include() and displays the logo; if the file doesn't exist it falls
back to the text title.
"""
import os, sys

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
PNG_PATH   = os.path.join(SCRIPT_DIR, "logo.png")
HDR_PATH   = os.path.join(SCRIPT_DIR, "LogoBinaryData.h")

if not os.path.exists(PNG_PATH):
    print(f"ERROR: logo.png not found at {PNG_PATH}")
    print("Copy your Bass Professor logo PNG there and re-run.")
    sys.exit(1)

with open(PNG_PATH, "rb") as f:
    data = f.read()

size = len(data)
hex_bytes = ", ".join(f"0x{b:02x}" for b in data)

header = f"""\
#pragma once
// AUTO-GENERATED by embed_logo.py — do not edit by hand.
// Re-run embed_logo.py whenever logo.png changes.
namespace LogoBinaryData
{{
    static const unsigned char logo_png[{size}] = {{ {hex_bytes} }};
    static const int logo_png_size = {size};
}}
"""

with open(HDR_PATH, "w") as f:
    f.write(header)

print(f"Written {size} bytes → {HDR_PATH}")
print("Now rebuild the Xcode project.")
